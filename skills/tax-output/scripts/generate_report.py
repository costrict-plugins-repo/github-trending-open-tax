#!/usr/bin/env python3
"""
Generate a human-readable Markdown summary report from computed tax data.

Usage:
    python3 generate_report.py <computed_data_dir> <output_dir>
"""

import json
import os
import sys
from datetime import datetime


def load_json(path):
    with open(path, 'r') as f:
        return json.load(f)


def fmt(amount):
    """Format a dollar amount with commas and 2 decimal places."""
    if amount < 0:
        return f"-${abs(amount):,.2f}"
    return f"${amount:,.2f}"


def main():
    if len(sys.argv) < 3:
        print("Usage: python3 generate_report.py <computed_data_dir> <output_dir>", file=sys.stderr)
        sys.exit(1)

    computed_dir = sys.argv[1]
    output_dir = sys.argv[2]

    # Load all computed data
    data = {}
    for name in ['tax_computation', 'se_tax', 'capital_gains', 'credits_and_final',
                  'crypto_lot_matching', 'crypto_income', 'wash_sale_analysis']:
        path = os.path.join(computed_dir, f'{name}.json')
        if os.path.exists(path):
            data[name] = load_json(path)

    tax = data.get('tax_computation', {})
    se = data.get('se_tax', {})
    cap = data.get('capital_gains', {})
    credits = data.get('credits_and_final', {})
    crypto_lots = data.get('crypto_lot_matching', {})
    crypto_inc = data.get('crypto_income', {})
    wash = data.get('wash_sale_analysis', {})

    gross = tax.get('gross_income', {})
    adjustments = tax.get('adjustments', {})
    final = credits.get('final_summary', {})
    credit_detail = credits.get('credits', {})

    lines = []
    lines.append(f"# Federal Tax Summary — Tax Year {tax.get('tax_year', 2025)}")
    lines.append(f"")
    lines.append(f"*Generated by Open Tax on {datetime.now().strftime('%B %d, %Y at %I:%M %p')}*")
    lines.append(f"")
    lines.append(f"> **Disclaimer**: This is a tax preparation aid, NOT professional tax advice.")
    lines.append(f"> Review all numbers before filing. See DISCLAIMER.md for full legal notice.")
    lines.append(f"")

    # Filing status
    status_display = tax.get('filing_status', 'single').replace('_', ' ').title()
    lines.append(f"**Filing Status**: {status_display}")
    lines.append(f"")

    # Income
    lines.append(f"## Income")
    lines.append(f"")
    lines.append(f"| Source | Amount |")
    lines.append(f"|---|---:|")
    if gross.get('wages', 0) > 0:
        lines.append(f"| W-2 Wages | {fmt(gross['wages'])} |")
    if gross.get('self_employment', 0) > 0:
        lines.append(f"| Self-Employment | {fmt(gross['self_employment'])} |")
    if gross.get('interest', 0) > 0:
        lines.append(f"| Interest | {fmt(gross['interest'])} |")
    if gross.get('ordinary_dividends', 0) > 0:
        lines.append(f"| Dividends | {fmt(gross['ordinary_dividends'])} |")
    if gross.get('capital_gains_net', 0) != 0:
        lines.append(f"| Capital Gains (Net) | {fmt(gross['capital_gains_net'])} |")
    if gross.get('crypto_ordinary_income', 0) > 0:
        lines.append(f"| Crypto Ordinary Income | {fmt(gross['crypto_ordinary_income'])} |")
    if gross.get('other', 0) > 0:
        lines.append(f"| Other Income | {fmt(gross['other'])} |")
    lines.append(f"| **Gross Income** | **{fmt(gross.get('total', 0))}** |")
    lines.append(f"")

    # Adjustments
    if adjustments.get('total', 0) > 0:
        lines.append(f"## Above-the-Line Adjustments")
        lines.append(f"")
        lines.append(f"| Adjustment | Amount |")
        lines.append(f"|---|---:|")
        for key, val in adjustments.items():
            if key == 'total' or val == 0:
                continue
            label = key.replace('_', ' ').title()
            lines.append(f"| {label} | {fmt(val)} |")
        lines.append(f"| **Total Adjustments** | **{fmt(adjustments['total'])}** |")
        lines.append(f"")

    # AGI and deductions
    lines.append(f"## Adjusted Gross Income & Deductions")
    lines.append(f"")
    lines.append(f"| Item | Amount |")
    lines.append(f"|---|---:|")
    lines.append(f"| AGI | {fmt(tax.get('agi', 0))} |")
    lines.append(f"| Deduction ({tax.get('deduction_method', 'standard').title()}) | {fmt(tax.get('deduction_amount', 0))} |")
    lines.append(f"| **Taxable Income** | **{fmt(tax.get('taxable_income', 0))}** |")
    lines.append(f"")

    # Tax liability
    lines.append(f"## Tax Liability")
    lines.append(f"")
    lines.append(f"| Tax | Amount |")
    lines.append(f"|---|---:|")
    lines.append(f"| Federal Income Tax | {fmt(final.get('federal_income_tax', tax.get('federal_income_tax', 0)))} |")
    if se.get('total_se_tax', 0) > 0:
        lines.append(f"| Self-Employment Tax | {fmt(se['total_se_tax'])} |")
    if final.get('long_term_capital_gains_tax', 0) > 0:
        lines.append(f"| Long-Term Capital Gains Tax | {fmt(final['long_term_capital_gains_tax'])} |")
    if final.get('net_investment_income_tax', 0) > 0:
        lines.append(f"| Net Investment Income Tax | {fmt(final['net_investment_income_tax'])} |")
    lines.append(f"| **Total Tax** | **{fmt(final.get('total_tax_before_credits', 0))}** |")
    lines.append(f"")

    # Credits
    if credit_detail.get('total_credits', 0) > 0:
        lines.append(f"## Credits")
        lines.append(f"")
        lines.append(f"| Credit | Amount |")
        lines.append(f"|---|---:|")
        ctc = credit_detail.get('child_tax_credit', {})
        if ctc.get('credit', 0) > 0:
            lines.append(f"| Child Tax Credit ({ctc.get('qualifying_children', 0)} children) | {fmt(ctc['credit'])} |")
        odc = credit_detail.get('other_dependent_credit', {})
        if odc.get('credit', 0) > 0:
            lines.append(f"| Other Dependent Credit | {fmt(odc['credit'])} |")
        lines.append(f"| **Total Credits** | **{fmt(credit_detail['total_credits'])}** |")
        lines.append(f"")

    # Payments and result
    lines.append(f"## Payments & Result")
    lines.append(f"")
    lines.append(f"| Item | Amount |")
    lines.append(f"|---|---:|")
    if final.get('tax_withheld', 0) > 0:
        lines.append(f"| Federal Tax Withheld | {fmt(final['tax_withheld'])} |")
    if final.get('estimated_payments', 0) > 0:
        lines.append(f"| Estimated Payments | {fmt(final['estimated_payments'])} |")
    if credit_detail.get('total_credits', 0) > 0:
        lines.append(f"| Total Credits | {fmt(credit_detail['total_credits'])} |")
    lines.append(f"")

    owed = final.get('amount_owed_or_refund', 0)
    if owed < 0:
        lines.append(f"### Refund: {fmt(abs(owed))}")
    elif owed > 0:
        lines.append(f"### Amount Owed: {fmt(owed)}")
    else:
        lines.append(f"### Balance: $0.00 (even)")
    lines.append(f"")

    eff_rate = final.get('effective_tax_rate', 0)
    lines.append(f"**Effective Tax Rate**: {eff_rate:.1f}%")
    lines.append(f"")

    # Crypto summary (if applicable)
    if crypto_lots.get('summary') or crypto_inc.get('total_crypto_income_usd', 0) > 0:
        lines.append(f"## Crypto / Digital Assets")
        lines.append(f"")
        summary = crypto_lots.get('summary', {})
        if summary:
            lines.append(f"| Metric | Value |")
            lines.append(f"|---|---:|")
            lines.append(f"| Transactions | {summary.get('total_transactions', 0)} |")
            lines.append(f"| Total Proceeds | {fmt(summary.get('total_proceeds', 0))} |")
            lines.append(f"| Total Cost Basis | {fmt(summary.get('total_cost_basis', 0))} |")
            lines.append(f"| Net Gain/Loss | {fmt(summary.get('total_gain_loss', 0))} |")
            lines.append(f"| Short-Term | {fmt(summary.get('short_term_gain', 0))} |")
            lines.append(f"| Long-Term | {fmt(summary.get('long_term_gain', 0))} |")
            lines.append(f"")
        if crypto_inc.get('total_crypto_income_usd', 0) > 0:
            lines.append(f"**Crypto Ordinary Income**: {fmt(crypto_inc['total_crypto_income_usd'])}")
            lines.append(f"")

    # Wash sales
    if wash.get('wash_sales_detected', 0) > 0:
        lines.append(f"## Wash Sale Flags")
        lines.append(f"")
        lines.append(f"**{wash['wash_sales_detected']}** potential wash sale(s) detected.")
        lines.append(f"Total disallowed loss: {fmt(wash.get('total_disallowed_loss', 0))}")
        lines.append(f"")
        lines.append(f"> {wash.get('disclaimer', 'Review with a tax professional.')}")
        lines.append(f"")

    lines.append(f"---")
    lines.append(f"*Generated by Open Tax v0.1.0 — not professional tax advice*")

    report = "\n".join(lines)

    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, "tax_summary_report.md")

    with open(output_path, 'w') as f:
        f.write(report)

    print(report)
    print(f"\nSaved to: {output_path}", file=sys.stderr)


if __name__ == '__main__':
    main()
